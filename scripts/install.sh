#!/usr/bin/env bash
# usage: scripts/install.sh [claude|opencode|all]
# copy .agents/ commands + agents into tool folders. edit .agents/, never the copies.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
HDR="<!-- generated by scripts/install.sh. edit .agents/ instead -->"
AGENT=.agents/agents/ralph.md

desc() { sed -n 's/^description: //p' "$1" | head -1; }
body() { awk 'NR==1&&/^---$/{fm=1;next} fm&&/^---$/{fm=0;next} !fm' "$1"; }
stamp() { awk -v h="$HDR" 'NR==1&&/^---$/{fm=1;print;next} fm&&/^---$/{print;print h;fm=0;next}{print}' "$1"; }

copy_commands() {  # $1 = target dir
  mkdir -p "$1"
  for f in .agents/commands/*.md; do stamp "$f" > "$1/$(basename "$f")"; done
}

install_claude() {
  copy_commands .claude/commands
  mkdir -p .claude/agents
  { printf -- '---\nname: ralph\ndescription: %s\ntools: Read, Edit, Write, Bash, Grep, Glob\nmodel: inherit\n---\n%s\n' \
      "$(desc "$AGENT")" "$HDR"; body "$AGENT"; } > .claude/agents/ralph.md
  [ -e .claude/skills ] || ln -s ../.agents/skills .claude/skills
  echo "claude: ok"
}

install_opencode() {
  copy_commands .opencode/commands   # check: your version may read .opencode/command/
  mkdir -p .opencode/agents
  { printf -- '---\ndescription: %s\nmode: subagent\n---\n%s\n' \
      "$(desc "$AGENT")" "$HDR"; body "$AGENT"; } > .opencode/agents/ralph.md
  echo "opencode: ok (skills read from .agents/skills)"
}

case "${1:-all}" in
  claude) install_claude ;;
  opencode) install_opencode ;;
  all) install_claude; install_opencode ;;
  *) echo "usage: $0 [claude|opencode|all]" >&2; exit 2 ;;
esac
