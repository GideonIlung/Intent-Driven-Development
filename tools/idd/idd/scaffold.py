"""Gherkin in scenarios → tests/features/<cap>.feature + pytest-bdd binding."""
from __future__ import annotations

import re

from . import parse
from .common import ROOT, Ctx, rel

BOX_TAG = re.compile(r"\s*\[[A-Z][A-Z0-9_]*\]\s*$")


def scaffold(ctx: Ctx) -> list[str]:
    m = ctx.model
    feat = ROOT / "tests" / "features" / f"{ctx.cap}.feature"
    feat.parent.mkdir(parents=True, exist_ok=True)
    out = [f"# generated by scripts/idd scaffold from specs + {ctx.slug}. do not edit.", f"Feature: {ctx.cap}", ""]
    for t in sorted(m.scenarios, key=parse.tag_key):
        for ln in m.scenarios[t].raw.splitlines():
            out.append("  " + BOX_TAG.sub("", ln.rstrip()).strip() if ln.strip() else "")
        out.append("")
    # indent steps under scenario
    fixed = []
    for ln in out:
        s = ln.strip()
        if re.match(r"(Given|When|Then|And|But)\b", s):
            fixed.append("    " + s)
        else:
            fixed.append(ln)
    feat.write_text("\n".join(fixed) + "\n")
    made = [rel(feat)]
    bind = ROOT / "tests" / "steps" / f"test_{ctx.cap}.py"
    if not bind.exists():
        bind.parent.mkdir(parents=True, exist_ok=True)
        bind.write_text(
            '"""Step definitions for the ' + ctx.cap + ' feature. Ralph fills these in."""\n'
            "from pytest_bdd import scenarios\n\n"
            f'scenarios("../features/{ctx.cap}.feature")\n'
        )
        made.append(rel(bind))
    return made
